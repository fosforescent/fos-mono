const { App, mountUi, createMemoryStorage, parseRowInput, view, argumentRefs, resolveScope, headCid, serializeReplica, loadReplica, LIBRARY_ID } = require(path.join(dir, 'app.cjs'))
const tick = () => new Promise(resolve => setImmediate(resolve))
const key = (input, name, mods = {}) => input.dispatchEvent(new window.KeyboardEvent('keydown', { key: name, bubbles: true, cancelable: true, ...mods }))
async function main() {
  assert.equal(parseRowInput('@alice').extras.allocation.type, 'person')
  assert.equal(parseRowInput('@alice').peer, undefined)
  const a = new App({ baseUrl: 'http://localhost', autoLogin: null, storage: createMemoryStorage(), scopedDocument: true })
  a.scheduleSync = () => {}; a.refreshRequests = async () => {}
  mountUi(document.getElementById('app'), a); await tick()
  let input = document.querySelector('.ghost textarea')
  input.focus(); input.value = '@{inv'; input.dispatchEvent(new window.Event('input'))
  assert.equal(input.getAttribute('aria-expanded'), 'true')
  assert(document.querySelector('.peer-autocomplete .combo-panel:not([hidden])').textContent.includes('@{invite}'))
  key(input, 'Enter'); await tick()
  let peer = a.currentView().tasks.find(t => t.construction?.handler === 'invite')
  assert.equal(argumentRefs(a.state.replica.store, resolveScope(a.state.replica.store, headCid(a.state.replica), [peer.id])).length, 0, 'peer braces are not template parameters')
  assert(peer, 'autocomplete creates an ordinary typed peer ref')
  assert.equal(a.currentView().tasks.length, 1, 'completion never commits a second partial peer')
  const loaded = loadReplica(serializeReplica(a.state.replica))
  assert(view(loaded, []).tasks.filter(t => t.id !== LIBRARY_ID).some(t => t.construction?.handler === 'invite'), 'peer constructor survives reload')
  assert(!document.querySelector('[aria-label="Peer connection type"]'))
  a.set({ session: { kind: 'user', username: 'alice', jwt: 'test', baseUrl: 'http://localhost' } })
  globalThis.fetch = async () => ({ ok: false, status: 503, statusText: 'Unavailable', json: async () => ({ error: 'Invite service unavailable' }) })
  document.querySelector('.task[data-id="' + peer.id + '"] .constructor-body button').click(); await tick(); await tick()
  assert(document.querySelector('.modal-body').textContent.includes('unavailable'))
  assert(!document.querySelector('.modal-body').textContent.includes('Creating an invite'))
  globalThis.fetch = async () => ({ ok: true, json: async () => ({ token: 'visible-test-invite', expiresAt: '2030-01-01', inviteId: 1 }) })
  ;[...document.querySelectorAll('.modal-body button')].find(b => b.textContent === 'Retry').click(); await tick(); await tick()
  assert.equal(document.querySelector('.modal-body .code-box textarea').value, 'visible-test-invite')
  a.closeModal(); a.goToRoot(); await tick()
  input = document.querySelector('.ghost textarea'); input.focus(); input.value = 'Feature'; key(input, 'Enter'); await tick()
  input = document.querySelector('.ghost textarea'); input.focus(); key(input, 'Tab'); await tick()
  assert.equal(a.state.selected.length, 2, 'Enter then Tab creates a child under the last committed row')
  input = document.activeElement; input.value = 'Nested detail'; input.dispatchEvent(new window.Event('commit-edit')); await tick()
  const feature = a.currentView().tasks.find(t => t.title === 'Feature')
  a.select([feature.id]); await tick()
  input = document.querySelector('.task[data-id="' + feature.id + '"] textarea.edit')
  const rowCount = a.currentView().tasks.length
  key(input, 'Enter', { shiftKey: true }); await tick()
  assert.equal(a.rowAt([feature.id]).branches.selected, 'branch 1')
  assert.equal(a.currentView().tasks.length, rowCount, 'Shift+Enter creates no sibling row')
  assert.equal(a.state.selected[0], feature.id, 'new branch keeps row focus')
  a.rewriteRowAt([], feature.id, parseRowInput('Changed feature'))
  a.toggleBranchMergeRequest([feature.id], 'branch 1')
  const names = a.rowAt([feature.id]).branches.mergeRequests
  assert.deepEqual(names, ['branch 1'])
  a.selectNodeBranch([], feature.id, 'main', true)
  assert.equal(a.rowAt([feature.id]).title, 'Feature', 'branch edits are isolated')
  assert.equal(view(a.state.replica, [feature.id]).tasks[0].title, 'Nested detail')
  assert(!document.querySelector('.view-switch'))
  assert(document.querySelector('[aria-label="Analyze node"] svg'))
  a.rewriteRowAt([], peer.id, parseRowInput('@{virtual}'))
  assert.equal(a.rowAt([peer.id]).construction.handler, 'virtual')
  a.rewriteRowAt([], peer.id, parseRowInput('Ordinary row'))
  assert.equal(a.rowAt([peer.id]).construction, undefined, 'removing peer syntax removes its constructor')
  console.log('PASS: peer autocomplete, invite error/retry/code, Enter+Tab, Shift+Enter, branch requests/isolation and distinct view icons')
}
main().catch(error => { console.error(error); process.exitCode = 1 }).finally(() => { dom.window.dispatchEvent(new dom.window.PageTransitionEvent('pagehide')); dom.window.close(); rmSync(dir, { recursive: true, force: true }) })
