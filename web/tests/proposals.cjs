const assert = require('node:assert/strict')
const { mkdtempSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const path = require('node:path')
const { buildSync } = require('esbuild')
const { JSDOM } = require('jsdom')
const dir = mkdtempSync(path.join(tmpdir(), 'fos-proposal-ui-'))
const dom = new JSDOM('<div id="app"></div>', { url: 'http://localhost/' })
for (const key of ['window', 'document', 'HTMLElement', 'HTMLInputElement', 'HTMLTextAreaElement', 'Node', 'Option', 'navigator', 'localStorage', 'sessionStorage', 'location']) Object.defineProperty(globalThis, key, { value: dom.window[key], configurable: true })
buildSync({ stdin: { contents: `export {App} from './src/app'; export {mountUi} from './src/ui'; export {createMemoryStorage} from './src/storage'; export * from '../shared/sync/index'`, resolveDir: path.resolve(__dirname, '..') }, bundle: true, platform: 'node', format: 'cjs', outfile: path.join(dir, 'app.cjs'), external: ['mermaid', 'katex', 'katex/*'] })
const { App, mountUi, createMemoryStorage, addTask, headCid, resolveScope, content, put, putStripped, proposalContent, readProposal, withProposal, makeLink, commitRoot, updateAtScope, view, rowEdgeAt, LIBRARY_ID } = require(path.join(dir, 'app.cjs'))
async function main() {
  const a = new App({ baseUrl: 'http://localhost', autoLogin: null, storage: createMemoryStorage(), scopedDocument: true })
  a.scheduleSync = () => {}
  mountUi(document.getElementById('app'), a)
  let r = addTask(a.state.replica, [], 'Project', 1, 'project')
  r = addTask(r, ['project'], 'Main child', 2, 'main-child')
  const s = r.store, cid = resolveScope(s, headCid(r), ['project']), base = putStripped(s, content(s, cid))
  const leaf = put(s, { data: { alias: { id: 'other-child' }, description: { content: 'Peer child' } }, children: [] })
  const branch = put(s, { data: { description: { content: 'Peer project' } }, children: [rowEdgeAt(s, 'plain', leaf, [])] })
  const proposal = put(s, proposalContent(s, 'other-peer', 'Other proposal', branch, base, 3))
  commitRoot(s, updateAtScope(s, headCid(r), ['project'], node => withProposal(s, makeLink(s, node, 3), 'other-peer', proposal, 'Other proposal'), 'node'), 4)
  a.set({ replica: { ...r } }); a.goTo(['project'])
  assert(!document.querySelector('.link-panel, [data-region="link"]'))
  assert(!document.querySelector('.tasks .constructor-row'), 'incoming branches are listed only in the branch caret')
  const pick = () => document.querySelector('.node-choices .alternative-picker input')
  document.querySelector('.node-choices .combo-trigger').click()
  let input = pick(); input.focus(); input.value = 'Other'; input.dispatchEvent(new window.Event('input')); a.refresh()
  assert.equal(document.activeElement, input); assert.equal(input.value, 'Other', 'sync preserves branch search draft')
  const options = [...document.getElementById(input.getAttribute('aria-controls')).querySelectorAll('[role=option]')]
  options.find(o => o.textContent.includes('Other proposal')).click()
  const before = headCid(a.state.replica)
  const text = document.querySelector('.current-node-row textarea')
  assert.equal(text.value, 'Peer project'); assert.equal(text.readOnly, true)
  assert(document.querySelector('.tasks').textContent.includes('Peer child'))
  assert(!document.querySelector('.tasks textarea.edit:not([readonly])'), 'read-only preview has no editable row cells')
  text.value = 'Attempted edit'; text.dispatchEvent(new window.Event('commit-edit'))
  document.body.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'z', ctrlKey: true, bubbles: true }))
  assert.equal(headCid(a.state.replica), before, 'preview does not change owner state or history')
  window.prompt = () => 'my-copy'
  ;[...document.querySelectorAll('button')].find(b => b.textContent === 'Copy to branch…').click()
  assert.equal(document.querySelector('.current-node-row textarea').readOnly, false)
  assert.equal(a.currentRow().branches.selected, 'my-copy')
  a.addTask('My edit')
  assert.equal(readProposal(s, proposal).contentCid, branch)
  document.querySelector('.node-choices .combo-trigger').click()
  input = pick(); input.value = 'main'; input.dispatchEvent(new window.Event('input')); input.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }))
  assert.deepEqual(view(a.state.replica, ['project']).tasks.map(t => t.title), ['Main child'])
  const title = document.querySelector('.current-node-row textarea').value
  assert(!document.querySelector('.view-switch'))
  assert(document.querySelector('[aria-label="Analyze node"]'))
  assert.equal(document.querySelector('.current-node-row textarea').value, title)
  document.querySelector('.node-choices .combo-trigger').click()
  input = pick(); input.value = 'scratch'; input.dispatchEvent(new window.Event('input'))
  input.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }))
  assert.equal(a.currentRow().branches.selected, 'scratch', 'typed branch name creates and selects an alternative')
  document.querySelector('.node-choices .combo-trigger').click()
  input = pick()
  assert(!document.querySelector('.combo-panel:not([hidden])').textContent.includes('Add child'))
  const request = document.querySelector('button[aria-label="Request merge: scratch"]')
  request.click()
  assert(a.currentRow().branches.mergeRequests.includes('scratch'))
  document.querySelector('.node-choices .combo-trigger').click()
  document.querySelector('button[aria-label="Request merge: scratch"]').click()
  assert(!a.currentRow().branches.mergeRequests.includes('scratch'))
  document.querySelector('.node-choices .combo-trigger').click()
  input = pick(); input.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))
  assert(document.activeElement.matches('.combo-trigger'), 'Escape returns to the trigger')
  document.activeElement.blur(); a.goToRoot(); a.select(['project'])
  await new Promise(resolve => setTimeout(resolve, 0))
  const editor = document.querySelector('.task[data-id="project"] textarea.edit')
  editor.value = 'Edited before opening'
  const trigger = document.querySelector('.task[data-id="project"] .combo-trigger')
  trigger.dispatchEvent(new window.MouseEvent('pointerdown', { button: 0, bubbles: true, cancelable: true }))
  await new Promise(resolve => setTimeout(resolve, 0))
  assert(document.querySelector('.task[data-id="project"] .combo-panel:not([hidden])'), 'committing a draft does not detach the opening popup')
  assert.equal(view(a.state.replica, []).tasks.filter(t => t.id !== LIBRARY_ID).find(t => t.id === 'project').title, 'Edited before opening')
  assert(document.activeElement.matches('.combo-panel input'), 'search retains focus after draft commit')
  console.log('PASS: branch merge-request constructors, unified picker, read-only preview, copy isolation, no link panel, child-only layouts')
}
main().catch(error => { console.error(error); process.exitCode = 1 }).finally(() => { dom.window.dispatchEvent(new dom.window.PageTransitionEvent('pagehide')); dom.window.close(); rmSync(dir, { recursive: true, force: true }) })
