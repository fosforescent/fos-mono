const assert = require('node:assert/strict')
const { buildSync } = require('esbuild')
const { mkdtempSync } = require('node:fs')
const path = require('node:path')
const { JSDOM } = require('jsdom')
const dir = mkdtempSync(path.join(require('node:os').tmpdir(), 'fos-ref-execution-'))
const dom = new JSDOM('<div id="app"></div>', { url: 'http://localhost/' })
for (const key of ['window', 'document', 'HTMLElement', 'HTMLInputElement', 'HTMLTextAreaElement', 'Node', 'Option', 'navigator', 'localStorage', 'sessionStorage', 'location']) Object.defineProperty(globalThis, key, { value: dom.window[key], configurable: true })
buildSync({ stdin: { contents: `export {App} from './src/app'; export {mountUi} from './src/ui'; export {createMemoryStorage} from './src/storage'; export * from '../shared/sync/index'`, resolveDir: path.resolve(__dirname, '..') }, bundle: true, platform: 'node', format: 'cjs', outfile: path.join(dir, 'test.cjs'), external: ['mermaid', 'katex', 'katex/*'] })
const c = require(path.join(dir, 'test.cjs'))

async function main() {
  const app = new c.App({ baseUrl: 'http://localhost', autoLogin: null, storage: c.createMemoryStorage() })
  app.scheduleSync = () => {}
  let r = c.addTask(app.state.replica, [c.HOME_ID], 'Work', 1, 'work')
  const text = r.store.primitive.documentField.getId(), root = [c.HOME_ID, 'work']
  const source = c.put(r.store, c.refNodeContent(r.store, { alias: { id: 'instruction-source' }, name: { content: 'source' } }, null, []))
  const instruction = c.put(r.store, { data: { description: { content: 'Custom instruction' } }, children: [[text, source]] })
  c.commitRoot(r.store, c.updateAtScope(r.store, c.headCid(r), [c.HOME_ID], node => ({ ...node, children: node.children.map(edge => c.content(r.store, edge[1]).data.alias?.id === 'work' ? [instruction, edge[1]] : edge) })), 2)
  const answer = c.put(r.store, c.refNodeContent(r.store, { alias: { id: 'answer' }, name: { content: 'Answer' }, refRole: 'output' }, null, []))
  r = c.addRefAt(r, root, 'result', c.put(r.store, { data: {}, children: [] }), 3, c.put(r.store, { data: {}, children: [[text, answer]] }), 'result')
  app.set({ replica: r, view: root })
  c.mountUi(document.getElementById('app'), app)
  assert.equal(document.querySelector('.evaluate').disabled, true, 'an instruction hole disables Run')
  await app.startExecution(root)
  assert.equal(app.executionPath(), null, 'the command checks the same condition as the button')
  r = c.addRefAt(app.state.replica, root, 'source', text, 4, c.put(r.store, { data: { description: { content: 'Ready' } }, children: [] }), 'source')
  app.set({ replica: r })
  assert.equal(document.querySelector('.evaluate').disabled, false, 'a right-side output hole does not block Run')
  await app.startExecution(root)
  await new Promise(resolve => setTimeout(resolve, 20))
  const input = document.querySelector('input[aria-label="Answer"]')
  assert(input, 'the execute form discovers nested product properties')
  input.value = 'Done'
  input.parentElement.querySelector('button').click()
  await new Promise(resolve => setTimeout(resolve, 20))
  assert.equal(c.resolveText(app.state.replica, root, '{.result.answer}').text, 'Done')
  assert(!document.querySelector('input[aria-label="Answer"]'), 'the filled hole leaves the input form')
  console.log('PASS: left-side Run gating, command recheck, right-side output holes and nested execute inputs')
  dom.window.close()
}
main().catch(error => { console.error(error); process.exitCode = 1; dom.window.close() })
